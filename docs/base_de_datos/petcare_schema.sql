CREATE OR REPLACE FUNCTION public.cambiar_estado_propietario(p_propietario_id bigint, p_accion text, p_motivo text DEFAULT NULL::text)
 RETURNS json
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
    v_estado TEXT;
    v_motivo TEXT;
BEGIN
    IF p_accion NOT IN ('activar', 'desactivar') THEN
        RAISE EXCEPTION 'La acción indicada no es válida.';
    END IF;

    IF p_accion = 'desactivar' THEN
        v_motivo := NULLIF(BTRIM(p_motivo), '');

        IF v_motivo IS NULL THEN
            RAISE EXCEPTION 'Debes ingresar el motivo de desactivación.';
        END IF;
    END IF;

    SELECT estado
    INTO v_estado
    FROM public.propietarios
    WHERE propietario_id = p_propietario_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'No se encontró el propietario.';
    END IF;

    IF p_accion = 'desactivar' THEN
        UPDATE public.mascotas
        SET estado = 'Inactivo',
            motivo_desactivacion = v_motivo,
            desactivada_por_propietario = TRUE
        WHERE propietario_id = p_propietario_id
          AND LOWER(TRIM(estado)) = 'activo';

        UPDATE public.propietarios
        SET estado = 'Inactivo',
            motivo_desactivacion = v_motivo
        WHERE propietario_id = p_propietario_id;
    ELSE
        UPDATE public.propietarios
        SET estado = 'Activo',
            motivo_desactivacion = NULL
        WHERE propietario_id = p_propietario_id;

        UPDATE public.mascotas
        SET estado = 'Activo',
            motivo_desactivacion = NULL,
            desactivada_por_propietario = FALSE
        WHERE propietario_id = p_propietario_id
          AND desactivada_por_propietario = TRUE;
    END IF;

    RETURN json_build_object(
        'correcto', TRUE,
        'accion', p_accion,
        'propietario_id', p_propietario_id
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.es_administrador_activo()
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO ''
AS $function$
    SELECT EXISTS (
        SELECT 1
        FROM public.perfiles AS p
        WHERE p.perfil_id = (SELECT auth.uid())
          AND p.rol = 'Administrador'
          AND p.estado_cuenta = 'Activo'
    );
$function$;

